"""Deterministic, scoped vanilla-JS factory composition; no JS rewriting/tools.

Each source is a factory expression with two dependency comments. Factories get
only their declared dependencies and their local declarations cannot collide.
Normal builds call verify(), which never writes checked-in sources.
"""
from pathlib import Path
import re

MODULES = (
    ("protocol", ()), ("commands", ()), ("state", ()),
    ("transport", ("protocol", "commands")), ("control", ()), ("actions", ()), ("preferences", ()), ("fader", ()),
    ("editor", ("fader",)), ("presets", ()), ("settings", ()),
    ("status", ()), ("shell", ()),
    ("app", ("state", "transport", "control", "actions", "preferences", "editor", "presets", "settings", "status", "shell")),
)
CORE = ("protocol", "commands", "state", "transport", "control", "actions", "preferences")
UI = ("fader", "editor", "presets", "settings", "status", "shell", "app")
OUTPUTS = ("core.js", "ui.js")


def compose(root, modules=MODULES):
    folder = Path(root) / "web/src/js"
    seen = set()
    pieces = {}
    for name, dependencies in modules:
        if not re.fullmatch(r"[a-z][a-z0-9_]*", name) or name in seen:
            raise ValueError("invalid/duplicate UI module: " + name)
        if len(set(dependencies)) != len(dependencies) or any(dep not in seen for dep in dependencies):
            raise ValueError("missing/out-of-order UI dependency: " + name)
        path = folder / (name + ".js")
        data = path.read_bytes().replace(b"\r\n", b"\n")
        text = data.decode("utf-8", errors="strict")
        expected = "// module: " + name + "\n// requires:" + (" " + ",".join(dependencies) if dependencies else "") + "\n"
        if not text.startswith(expected) or not text[len(expected):].strip() or "\x00" in text or "\r" in text or len(data) > 65536:
            raise ValueError("invalid UI module/dependency declaration: " + name)
        pieces[name] = '\n'.join(['// Source: web/src/js/' + name + '.js', 'const ' + name + ' = (',
                                  text.rstrip(), ')({' + ', '.join(dependencies) + '});', ''])
        seen.add(name)
    actual = {p.stem for p in folder.glob("*.js")}
    if actual != seen or seen != set(CORE + UI):
        raise ValueError("missing/unlisted UI modules: " + repr(sorted(actual ^ seen)))
    loader = (Path(root) / "web/src/loader.js").read_bytes().replace(b"\r\n", b"\n").decode("utf-8", errors="strict")
    if any(loader.count(token) != 1 for token in ("/* CORE_FACTORIES */", "/* CORE_EXPORTS */")):
        raise ValueError("invalid bootstrap template")
    banner = '// Generated by scripts/web_ui_bundle.py; edit factories/loader sources.\n'
    core = loader.replace('/* CORE_FACTORIES */', '\n'.join(pieces[name] for name in CORE)).replace(
        '/* CORE_EXPORTS */', ', '.join(CORE))
    ui = '\n'.join(['(function () {', '"use strict";',
        'window.__CoreS3SEBoot.mount(({' + ', '.join(CORE) + '}) => {',
        *(pieces[name] for name in UI), 'return app;', '});', '})();', ''])
    return {"core.js": (banner + core).encode("utf-8"), "ui.js": (banner + ui).encode("utf-8")}


def verify(root):
    expected = compose(root)
    for name, data in expected.items():
        path = Path(root) / "web/src" / name
        if not path.is_file() or path.read_bytes().replace(b"\r\n", b"\n") != data:
            raise ValueError("stale UI bundle: " + name + "; run python scripts/web_asset_pipeline.py --generate")
    if (Path(root) / "web/src/app.js").exists():
        raise ValueError("obsolete single UI bundle: app.js")
    return expected


def generate(root):
    outputs = compose(root)
    for name, data in outputs.items():
        path = Path(root) / "web/src" / name
        if not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)
    (Path(root) / "web/src/app.js").unlink(missing_ok=True)
    return outputs
